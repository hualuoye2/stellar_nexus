def _check_rift_lanes() -> None:
    """导入时断言：每条暗带的银经必须单调递增。

    这是针对"区间插值失效"这类缺陷的不变量检查。银经跨 0° 时用 360~440
    这样的连续值表示（milky_way_rift_at 会把查询银经也加 360 再试一次）。
    """
    for i, lane in enumerate(MILKY_RIFT_LANES):
        for j in range(len(lane) - 1):
            if lane[j + 1][0] <= lane[j][0]:
                raise ValueError(
                    f"银河暗带 #{i} 的银经非单调递增：{lane[j][0]} → {lane[j + 1][0]}"
                    f"（插值会全部落空，暗带失效）")


def milky_way_brightness(l_deg: float) -> float:
    """银经 → 银河带的相对表面亮度（0.25 ~ 1.0）。

    控制点之间线性插值；超出范围时按首尾值处理。
    这是给渲染层调透明度用的无量纲量，不是物理单位。
    """
    pts = MILKY_LONGITUDE_BRIGHTNESS
    x = l_deg % 360.0
    for i in range(len(pts) - 1):
        x0, y0 = pts[i]
        x1, y1 = pts[i + 1]
        if x0 <= x <= x1:
            if x1 == x0:
                return y0
            return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    return pts[-1][1]


def milky_way_rift_at(l_deg: float, b_deg: float) -> float:
    """给定银道坐标，返回被暗带遮光的比例（0 = 完全透明，1 = 完全遮住）。

    实现要点（这里出过一次错，记下来）：
      控制点只覆盖暗带**实际存在的银经区间**（主暗带 0~80°，侧支更短），
      所以落在区间外的银经必须迅速衰减到 0。第一版对区间外的点按 25° 的
      高斯衰减，结果 l=180（反银心）仍算出 0.50 的遮挡——整条银河被均匀
      压暗了一半，看起来像"没有暗带"，与没做这个功能几乎没区别。
      现在改用 8° 的衰减尺度，并额外要求 |b| 在带内。
    """
    x = l_deg % 360.0
    total = 0.0
    for lane in MILKY_RIFT_LANES:
        # 银经可能跨 0°（控制点用 360~440 表示），所以查询值也试一次 x+360
        seg = None
        for xq in (x, x + 360.0):
            for i in range(len(lane) - 1):
                l0, b0, w0, s0 = lane[i]
                l1, b1, w1, s1 = lane[i + 1]
                if l0 <= xq <= l1:
                    t = 0.0 if l1 == l0 else (xq - l0) / (l1 - l0)
                    seg = (b0 + (b1 - b0) * t, w0 + (w1 - w0) * t, s0 + (s1 - s0) * t)
                    break
            if seg is not None:
                break
        if seg is None:
            # 落在控制点区间外：用最近端点，但必须迅速衰减到 0。
            # 距离按"银经环形距离"算：端点银经可能写成 360~440，先折回 0~360。
            l0, b0, w0, s0 = lane[0]
            l1, b1, w1, s1 = lane[-1]
            e0, e1 = l0 % 360.0, l1 % 360.0
            d0 = min((x - e0) % 360.0, (e0 - x) % 360.0)
            d1 = min((x - e1) % 360.0, (e1 - x) % 360.0)
            if d0 <= d1:
                b_c, w_c, s_c, d = b0, w0, s0, d0
            else:
                b_c, w_c, s_c, d = b1, w1, s1, d1
            seg = (b_c, w_c, s_c * math.exp(-(d / 8.0) ** 2))
        b_c, w_c, s_c = seg
        if s_c <= 0.01:
            continue
        db = b_deg - b_c
        total = max(total, s_c * math.exp(-(db / max(0.3, w_c)) ** 2))
    return clamp(total, 0.0, 0.95)


def milky_way_rift_peak(l_deg: float, coarse: float = 1.0) -> Tuple[float, float]:
    """返回该银经下暗带的 (中心银纬, 遮挡强度)，用**二分 + 粗扫**求峰。

    单独抽成函数是为了给渲染层缓存：暗带中心只随银经变化，与时间/视角无关，
    所以界面可以在首次绘制时算一次（约 181 个银经点）然后一直复用。
    直接在 milky_way_rift_at 上做 0.5° 粗扫（每帧 × 181 银经 × 41 银纬）实测
    要 70 ms/帧，是整个银河图层的主要开销。
    """
    lo, hi = -10.0, 10.0
    # 先粗扫定位峰所在的小区间
    best_b, best_s = 0.0, 0.0
    b = lo
    while b <= hi + 1e-9:
        s = milky_way_rift_at(l_deg, b)
        if s > best_s:
            best_s, best_b = s, b
        b += coarse
    if best_s <= 0.0:
        return (0.0, 0.0)
    # 再在 ±coarse 内三分搜索细化中心（遮挡函数在峰附近是单峰的）
    a_, b_ = best_b - coarse, best_b + coarse
    for _ in range(12):
        m1 = a_ + (b_ - a_) / 3.0
        m2 = b_ - (b_ - a_) / 3.0
        if milky_way_rift_at(l_deg, m1) < milky_way_rift_at(l_deg, m2):
            a_ = m1
        else:
            b_ = m2
    center = (a_ + b_) / 2.0
    return (center, milky_way_rift_at(l_deg, center))


def milky_way_profile(x: float) -> float:
    """银河带的**径向亮度剖面**：x = 0 在带心，x = ±1 在带缘，返回 0~1。

    改用平滑剖面替换原先的矩形核（那是"精细度不够"的根源）：
    原来的写法是 `half = b_max·(1−frac)·(0.55+0.45·亮度)`，即每一层的边界
    随层级**线性**收缩——多层叠起来在带内是一条**阶梯**而不是平滑梯度，
    视觉上就是几道平行的竖条纹，看起来又脏又不自然。

    现在改成：让第 k 层的边界落在满足 `profile(x) = k/levels` 的 x 上。
    因为 profile 是单调递减的，各层边界会自动按亮度曲线聚拢/散开，
    叠加后的 alpha 就是 profile 的连续近似。
    形状取「中心平顶 + 边缘高斯衰减」：真实银河在 |b| ≲ 2° 内亮度接近均匀，
    再往外快速衰减，所以用指数 2.5 的幂次做过渡最接近。
    """
    t = min(1.0, abs(float(x)))
    return math.exp(-2.5 * (t ** 2.5))


def milky_way_contours(levels: int = 9, b_max: float = 11.0,
                       step_deg: float = 3.0) -> List[Tuple[float, List[float], List[float],
                                                               List[float], List[float], List[float]]]:
    """等照度轮廓：返回 [(层级 0~1, 上边界赤经, 上边界赤纬, 下边界赤经, 下边界赤纬, 相对亮度)]。

    与 milky_way_points() 的区别：后者是**固定银纬**的几何带，本函数按
    "亮度等值线"给出随银经收放的边界，能表现"银心附近又宽又亮、
    反银心又窄又暗"的真实形态。

    注意返回值里必须同时有赤经**和赤纬**——只给赤经是画不出曲线的
    （第一版就漏了赤纬，调用方拿到两个 RA 列表根本没法投影）。
    """
    out: List[Tuple[float, List[float], List[float],
                    List[float], List[float], List[float]]] = []
    try:
        for level in range(levels):
            frac = (level + 1) / float(levels)          # 0~1，越大越靠内
            # 该层的边界应落在 profile(x) = frac 的位置（见 milky_way_profile）
            if frac >= 1.0:
                x_edge = 0.0
            else:
                x_edge = (-math.log(frac) / 2.5) ** (1.0 / 2.5)
            x_edge = clamp(x_edge, 0.0, 1.0)
            ra_u: List[float] = []
            de_u: List[float] = []
            ra_d: List[float] = []
            de_d: List[float] = []
            rel: List[float] = []
            l = 0.0
            while l <= 360.0:
                bright = milky_way_brightness(l)
                # 亮度越高带越宽：银心带比反银心宽约 2 倍
                half = b_max * (0.55 + 0.45 * bright) * x_edge
                u = galactic_to_equatorial(l, half)
                d = galactic_to_equatorial(l, -half)
                ra_u.append(u[0])
                de_u.append(u[1])
                ra_d.append(d[0])
                de_d.append(d[1])
                rel.append(bright)
                l += step_deg
            out.append((frac, ra_u, de_u, ra_d, de_d, rel))
    except Exception as exc:
        LOG.error("银河等照度轮廓采样失败", exc)
    return out


