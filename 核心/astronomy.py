def altitude_curve(ra_deg: float, dec_deg: float, observer: Observer,
                   hours_span: float = 24.0, samples: int = 96) -> List[Tuple[float, float]]:
    """计算某天体在未来 hours_span 小时内的高度角曲线，用于绘制升落示意。"""
    pts: List[Tuple[float, float]] = []
    try:
        step = hours_span / max(1, samples)
        for i in range(samples + 1):
            t = observer.when + timedelta(hours=i * step - hours_span / 2.0)
            jd = julian_date(t) - observer.utc_offset / 24.0
            lst = local_sidereal_time(jd, observer.lon)
            alt = equatorial_to_horizontal(ra_deg, dec_deg, lst, observer.lat)[0]
            pts.append((i * step - hours_span / 2.0, alt))
    except Exception as exc:
        LOG.error("高度角曲线计算失败", exc)
    return pts


@dataclass
class RiseSetInfo:
    """天体的升落信息（用于信息面板与状态提示）。"""

    alt: float = 0.0                    # 当前高度角（度）
    above: bool = False                 # 当前是否在地平线以上
    next_event: str = "—"               # "升起" / "落下" / "—"
    next_time: Optional[datetime] = None
    hours_until: Optional[float] = None
    rise_time: Optional[datetime] = None
    set_time: Optional[datetime] = None
    circumpolar: bool = False           # 拱极（永不落下）
    never_rises: bool = False           # 永不升起
    peak_alt: float = 0.0               # 未来 24 小时内的最大高度角

    def describe(self) -> str:
        """一行中文描述，界面直接显示。"""
        if self.circumpolar:
            return f"拱极天体（永不落下，当前高度 {self.alt:+.1f}°）"
        if self.never_rises:
            return "永不升起（该纬度看不到）"
        if self.next_time is None:
            return "未来 48 小时内无升落事件"
        when = self.next_time.strftime("%m-%d %H:%M")
        hours = self.hours_until or 0.0
        span = f"{hours:.1f} 小时" if hours < 24 else f"{hours / 24:.1f} 天"
        return f"约 {span}后{self.next_event}（{when}）"


def rise_set_info(ra_deg: float, dec_deg: float, observer: Observer,
                  hours_ahead: float = 48.0, step_minutes: float = 4.0) -> RiseSetInfo:
    """计算天体未来 hours_ahead 小时内的升落时刻。

    算法：以 step_minutes 为步长采样高度角，寻找 0° 穿越点（上升沿=升起，下降沿=落下），
    再对相邻两点做线性插值得到分钟级精度。对目视星图而言完全够用。
    """
    info = RiseSetInfo()
    try:
        info.circumpolar = is_circumpolar(dec_deg, observer.lat)
        info.never_rises = never_rises(dec_deg, observer.lat)
        info.alt = observer.altitude(ra_deg, dec_deg)
        info.above = info.alt > 0.0

        step = max(0.5, float(step_minutes))
        samples = int(clamp(hours_ahead * 60.0 / step, 24, 1440))
        prev_t: Optional[datetime] = None
        prev_alt: Optional[float] = None
        events: List[Tuple[datetime, str]] = []
        peak = -90.0
        for i in range(samples + 1):
            t = observer.when + timedelta(minutes=i * step)
            jd = julian_date(t) - observer.utc_offset / 24.0
            lst = local_sidereal_time(jd, observer.lon)
            alt = equatorial_to_horizontal(ra_deg, dec_deg, lst, observer.lat)[0]
            peak = max(peak, alt)
            if prev_alt is not None and prev_t is not None:
                if prev_alt < 0.0 <= alt:
                    # 线性插值求穿越时刻
                    k = (0.0 - prev_alt) / max(1e-9, alt - prev_alt)
                    events.append((prev_t + timedelta(minutes=step * k), "升起"))
                elif prev_alt >= 0.0 > alt:
                    k = (prev_alt - 0.0) / max(1e-9, prev_alt - alt)
                    events.append((prev_t + timedelta(minutes=step * k), "落下"))
            prev_t, prev_alt = t, alt
        info.peak_alt = round(peak, 1)

        # 取"下一次"发生的事件：在上的找落下，在下的找升起
        wanted = "落下" if info.above else "升起"
        for t, kind in events:
            if kind == wanted:
                info.next_event = kind
                info.next_time = t
                info.hours_until = (t - observer.when).total_seconds() / 3600.0
                break
        for t, kind in events:
            if kind == "升起" and info.rise_time is None:
                info.rise_time = t
            elif kind == "落下" and info.set_time is None:
                info.set_time = t
    except Exception as exc:
        LOG.error("升落计算失败", exc)
    return info


def is_circumpolar(dec_deg: float, lat_deg: float) -> bool:
    """是否拱极星（永不落下）。"""
    return dec_deg > (90.0 - abs(lat_deg))


def never_rises(dec_deg: float, lat_deg: float) -> bool:
    """是否永不升起。"""
    return dec_deg < -(90.0 - abs(lat_deg))


