def _vsop_series(terms: Sequence[Tuple[float, float, float, float, float]],
                 tau: float) -> float:
    """计算一阶级数：Σ A·cos(B + C·τ)。"""
    total = 0.0
    for a, b, c, _s, _k in terms:
        total += a * math.cos(b + c * tau)
    return total


def _heliocentric_ecliptic(planet: str, jd: float) -> Tuple[float, float, float]:
    """行星的日心黄道坐标（VSOP87D，参考历元的平黄道）。

    返回 (黄经 lon 度, 黄纬 lat 度, 距离 r 天文单位)
    """
    table = VSOP87_TERMS.get(planet)
    if not table:
        return (0.0, 0.0, 1.0)
    tau = (jd - J2000) / 365250.0  # 儒略千年数
    lon = norm360((_vsop_series(table["L"], tau)) * R2D)
    lat = _vsop_series(table["B"], tau) * R2D
    r = _vsop_series(table["R"], tau)
    return (lon, lat, r)


def _heliocentric_xyz(planet: str, jd: float) -> Tuple[float, float, float]:
    """行星的日心直角坐标（黄道参考系，单位 AU）。"""
    lon, lat, r = _heliocentric_ecliptic(planet, jd)
    cl = math.cos(lat * D2R)
    return (r * cl * math.cos(lon * D2R), r * cl * math.sin(lon * D2R), r * math.sin(lat * D2R))


def _precess_vector_to_date(vec: Sequence[float], jd: float) -> Tuple[float, float, float]:
    """把 J2000 平黄道向量转到「观测时刻的平黄道」。

    VSOP87D 的参考系是 J2000 平黄道，而实际观测需要历元平黄道，
    这里用 IAU1976 岁差角做一次旋转（对行星位置影响约 0.3°/世纪，必须修正）。
    """
    t = julian_centuries(jd)
    # 黄道岁差角（角秒）：π_A 描述黄道经度原点的移动，η（Π_A）描述黄道面倾角变化
    eta = (47.0029 * t - 0.03302 * t * t + 0.000060 * t ** 3) / 3600.0
    pi_a = 174.876383889 + (-869.8089 * t - 0.03536 * t ** 2) / 3600.0
    # 标准黄道岁差旋转：R = Rz(-π_A) · Rx(η) · Rz(π_A)
    return _rot_z(_rot_x(_rot_z(vec, -pi_a), eta), pi_a)


def planet_position(planet: str, jd: float) -> Dict[str, float]:
    """行星的地心视位置。入参 jd 为**世界时**儒略日，内部换算到力学时。

    流程：
        1. VSOP87 求行星日心坐标（J2000 平黄道）
        2. 光行时迭代：行星位置取自 (jd - τ) 时刻
        3. 减去地球位置得到地心向量
        4. 岁差修正到历元平黄道 → 转赤道坐标（视位置）

    ΔT 对行星的影响比月亮小得多（行星自行约 0.04″/秒，ΔT=75 秒 → 3″），
    但换算成本为零，且能让"行星 vs 月亮"的相对位置保持一致。
    """
    jd = jd_tt(jd)
    if planet == "earth":
        lon, lat, r = _heliocentric_ecliptic("earth", jd)
        ra, dec = ecliptic_to_equatorial(lon, lat, jd)
        return {"ra": ra, "dec": dec, "distance": r, "lon": lon, "lat": lat,
                "name": PLANET_NAMES_CN["earth"], "name_en": "Earth"}
    try:
        earth = _heliocentric_xyz("earth", jd)
        target = _heliocentric_xyz(planet, jd)
        # --- 光行时迭代（2 次即可收敛到 1e-6 AU） ---
        for _ in range(2):
            d = (target[0] - earth[0], target[1] - earth[1], target[2] - earth[2])
            dist = math.sqrt(d[0] ** 2 + d[1] ** 2 + d[2] ** 2)
            tau = dist / LIGHT_AU_PER_DAY          # 光行时（天）
            target = _heliocentric_xyz(planet, jd - tau)
        d = (target[0] - earth[0], target[1] - earth[1], target[2] - earth[2])
        dist = math.sqrt(d[0] ** 2 + d[1] ** 2 + d[2] ** 2)
        # --- 岁差修正 + 转赤道 ---
        v = _precess_vector_to_date(d, jd)
        lon = norm360(math.atan2(v[1], v[0]) * R2D)
        lat = math.asin(clamp(v[2] / max(1e-12, math.sqrt(v[0] ** 2 + v[1] ** 2 + v[2] ** 2)), -1, 1)) * R2D
        ra, dec = ecliptic_to_equatorial(lon, lat, jd)
        return {"ra": ra, "dec": dec, "distance": dist, "lon": lon, "lat": lat,
                "name": PLANET_NAMES_CN.get(planet, planet),
                "name_en": PLANET_NAMES_EN.get(planet, planet)}
    except Exception as exc:
        LOG.error(f"planet_position({planet}) 失败", exc)
        return {"ra": 0.0, "dec": 0.0, "distance": 1.0, "lon": 0.0, "lat": 0.0,
                "name": PLANET_NAMES_CN.get(planet, planet), "name_en": planet}


