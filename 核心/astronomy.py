"""
astronomy.py —— 天文算法核心（纯 Python 实现）
================================================================================
本模块实现了「现实星图」所需的全部天文计算，刻意不依赖 Skyfield / Astropy
等重型库，方便 PyInstaller 打包：

  1. 时间系统      ：公历 → 儒略日（JD）、儒略世纪 T、格林尼治/地方恒星时
  2. 坐标变换      ：赤道坐标 ↔ 地平坐标（高度角/方位角）、黄道 ↔ 赤道、银道 ↔ 赤道
  3. 岁差修正      ：J2000 平赤道 → 观测时刻平赤道（IAU 1976 简化模型）
  4. 太阳位置      ：Meeus 低精度太阳理论（精度约 0.01°）
  5. 月亮位置      ：Meeus 截断 ELP2000-82B（精度约 10 角分，视觉完全够用）
  6. 行星位置      ：VSOP87D 截断级数 + 光行时迭代 + 岁差 + 视差
  7. 大气折射      ：Saemundsson 公式（低空目标抬高，更接近真实观感）
  8. 工具          ：方位角→中文方位、地平高度角曲线（用于升落判断）

所有公开函数都做了异常保护，输入非法时返回安全默认值而不是抛异常。
术语约定：
    * 角度单位统一为「度」，内部三角函数使用弧度
    * RA  = 赤经（Right Ascension，度，0~360）
    * Dec = 赤纬（Declination，度，-90~90）
    * Alt = 高度角（Altitude，度，地平线以上为正）
    * Az  = 方位角（Azimuth，度，从正北起顺时针：北0 东90 南180 西270）
"""

