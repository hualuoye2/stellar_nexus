    (80.0, 0.72),     # 天鹅座星云（北天最亮段）
    (100.0, 0.52),
    (130.0, 0.40),
    (160.0, 0.32),
    (180.0, 0.30),    # 反银心 —— 最暗
    (200.0, 0.33),
    (230.0, 0.40),
    (260.0, 0.52),
    (290.0, 0.72),
    (310.0, 0.95),    # 人马-船底臂（南天最亮段）
    (330.0, 1.00),
