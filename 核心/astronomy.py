@dataclass
class Observer:
    """观测者：地理位置 + 观测时刻（本地时间）+ 时区。"""

    lat: float = 39.9042
    lon: float = 116.4074
    when: datetime = field(default_factory=datetime.now)
    utc_offset: float = 8.0
    location_name: str = "北京"
    elevation_m: float = 30.0

    # ---- 时间/恒星时 ----
    @property
    def jd_ut(self) -> float:
        """观测时刻对应的世界时儒略日（本地时间减去时区偏移）。"""
        try:
            return julian_date(self.when) - self.utc_offset / 24.0
        except Exception:
            return J2000

    @property
    def lst(self) -> float:
        """地方平恒星时（度）。"""
        return local_sidereal_time(self.jd_ut, self.lon)

    def radec_to_altaz(self, ra: float, dec: float) -> Tuple[float, float]:
        """赤道 → 地平（含大气折射）。"""
        alt, az = equatorial_to_horizontal(ra, dec, self.lst, self.lat)
        return (apply_refraction(alt), az)

    def altitude(self, ra: float, dec: float) -> float:
        """仅取高度角（不含大气折射，用于升落判断）。"""
        return equatorial_to_horizontal(ra, dec, self.lst, self.lat)[0]

    def to_utc(self) -> datetime:
        """本地时间 → UTC（带 tzinfo）。"""
        return self.when - timedelta(hours=self.utc_offset)

    def describe(self) -> str:
        """一行摘要，用于状态栏。"""
        return (f"{self.location_name}  {self.lat:+.3f}°, {self.lon:+.3f}°  "
                f"UTC{self.utc_offset:+.1f}  LST {self.lst / 15.0:05.2f}h")


