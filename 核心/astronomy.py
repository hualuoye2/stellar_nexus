def _rot_x(v: Sequence[float], deg: float) -> Tuple[float, float, float]:
    """绕 X 轴旋转（角度制），返回新向量。"""
    a = deg * D2R
    ca, sa = math.cos(a), math.sin(a)
    x, y, z = v[0], v[1], v[2]
    return (x, y * ca - z * sa, y * sa + z * ca)


def _rot_y(v: Sequence[float], deg: float) -> Tuple[float, float, float]:
    """绕 Y 轴旋转（角度制）。"""
    a = deg * D2R
    ca, sa = math.cos(a), math.sin(a)
    x, y, z = v[0], v[1], v[2]
    return (x * ca + z * sa, y, -x * sa + z * ca)


def _rot_z(v: Sequence[float], deg: float) -> Tuple[float, float, float]:
    """绕 Z 轴旋转（角度制）。"""
    a = deg * D2R
    ca, sa = math.cos(a), math.sin(a)
    x, y, z = v[0], v[1], v[2]
    return (x * ca - y * sa, x * sa + y * ca, z)


def radec_to_vec(ra_deg: float, dec_deg: float) -> Tuple[float, float, float]:
    """赤道坐标（赤经、赤纬，度）→ 单位向量。

    方向约定：X 指向春分点，Z 指向北天极，Y 完成右手系。
    """
    ra, dec = ra_deg * D2R, dec_deg * D2R
    cd = math.cos(dec)
    return (cd * math.cos(ra), cd * math.sin(ra), math.sin(dec))


def vec_to_radec(v: Sequence[float]) -> Tuple[float, float]:
    """单位向量 → (赤经, 赤纬)（度）。"""
    x, y, z = v[0], v[1], v[2]
    r = math.sqrt(x * x + y * y + z * z)
    if r < 1e-12:
        return (0.0, 0.0)
    dec = math.asin(clamp(z / r, -1.0, 1.0)) * R2D
    ra = norm360(math.atan2(y, x) * R2D)
    return (ra, dec)


def precess(ra_deg: float, dec_deg: float, jd_from: float, jd_to: float) -> Tuple[float, float]:
    """岁差修正：把 jd_from 历元的平赤道坐标转到 jd_to 历元的平赤道坐标。

    使用 IAU 1976 岁差角（ζ / z / θ）的向量旋转形式，避免球面三角的奇点问题。
    """
    try:
        t0 = julian_centuries(jd_from)
        t = julian_centuries(jd_to)
        dt = t - t0
        # 岁差角（角秒）
        zeta = (2306.2181 * dt + 0.30188 * dt ** 2 + 0.017998 * dt ** 3) / 3600.0
        z = (2306.2181 * dt + 1.09468 * dt ** 2 + 0.018203 * dt ** 3) / 3600.0
        theta = (2004.3109 * dt - 0.42665 * dt ** 2 - 0.041833 * dt ** 3) / 3600.0
        v = _rot_z(_rot_y(_rot_z(radec_to_vec(ra_deg, dec_deg), -zeta), theta), -z)
        return vec_to_radec(v)
    except Exception:
        return (ra_deg, dec_deg)


def ecliptic_to_equatorial(lon_deg: float, lat_deg: float, jd: float) -> Tuple[float, float]:
    """黄道坐标（黄经、黄纬）→ 赤道坐标（赤经、赤纬），单位度。"""
    eps = mean_obliquity(jd)
    v = _rot_x((math.cos(lat_deg * D2R) * math.cos(lon_deg * D2R),
                math.cos(lat_deg * D2R) * math.sin(lon_deg * D2R),
                math.sin(lat_deg * D2R)), eps)
    return vec_to_radec(v)


def equatorial_to_ecliptic(ra_deg: float, dec_deg: float, jd: float) -> Tuple[float, float]:
    """赤道坐标 → 黄道坐标（黄经、黄纬）。"""
    eps = mean_obliquity(jd)
    v = _rot_x(radec_to_vec(ra_deg, dec_deg), -eps)
    lon = norm360(math.atan2(v[1], v[0]) * R2D)
    lat = math.asin(clamp(v[2], -1.0, 1.0)) * R2D
    return (lon, lat)


#: 银道坐标系北极（J2000 赤道坐标）与银经零点
GAL_POLE_RA, GAL_POLE_DEC = 192.85948, 27.12825
GAL_LON_NODE = 32.93192  # 银经 0° 对应的赤经方向修正角


def _rot_axis(v: Sequence[float], deg: float, axis: int, forward: bool = True) -> Tuple[float, float, float]:
    """绕指定坐标轴旋转（forward=True 为逆时针正向旋转）。

    与 _rot_x / _rot_y / _rot_z 等价，但可以按轴号调用，便于算法推导时复用。
    """
    a = (deg if forward else -deg) * D2R
    ca, sa = math.cos(a), math.sin(a)
    x, y, z = v[0], v[1], v[2]
    if axis == 0:
        return (x, y * ca - z * sa, y * sa + z * ca)
    if axis == 1:
        return (x * ca + z * sa, y, -x * sa + z * ca)
    return (x * ca - y * sa, x * sa + y * ca, z)


def _galactic_basis() -> Tuple[Tuple[float, float, float],
                               Tuple[float, float, float],
                               Tuple[float, float, float]]:
    """构造银道系三根基轴在 J2000 赤道系中的单位向量 R。

        第 0 行 = x_gal   (l=0,  b=0)  = 银心方向（人马座 A*，赤经 266.405°、赤纬 −28.936°）
        第 1 行 = y_gal   (l=90, b=0)  = z_gal × x_gal
        第 2 行 = z_gal   (b=+90)      = 银北极（赤经 192.85948°、赤纬 +27.12825°）

    即 R[i][j] = 第 i 根基轴在赤道系的第 j 个分量。于是两个方向互转就是
    **同一对正交矩阵的转置关系**：

        v_eq  = Rᵀ · v_gal      （银道 → 赤道，见 galactic_to_equatorial）
        v_gal = R  · v_eq       （赤道 → 银道，见 equatorial_vector_to_galactic）

    这三行不是随手写的常数：x_gal 与 z_gal 取实测方向，y_gal 由叉积保证正交，
    行列式 +1（右手系）。自检见 _gal_check()。
    """
    ra_c, dec_c = 266.40510, -28.93617        # 银心方向（人马座 A*）
    ra_p, dec_p = GAL_POLE_RA, GAL_POLE_DEC   # 银北极

    def _unit(ra_deg: float, dec_deg: float) -> Tuple[float, float, float]:
        r, d = ra_deg * D2R, dec_deg * D2R
        return (math.cos(d) * math.cos(r), math.cos(d) * math.sin(r), math.sin(d))

    row_x = _unit(ra_c, dec_c)
    row_z = _unit(ra_p, dec_p)
    row_y = _cross(row_z, row_x)
    return (row_x, row_y, row_z)


def _cross(a: Sequence[float], b: Sequence[float]) -> Tuple[float, float, float]:
    """三维向量叉积。"""
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


#: 银道系三根基轴在赤道系中的单位向量，R[i] = 第 i 根基轴。
#:     v_eq  = Rᵀ · v_gal      （银道 → 赤道）
#:     v_gal = R  · v_eq       （赤道 → 银道）
_GAL_MATRIX: Tuple[Tuple[float, float, float], ...] = _galactic_basis()


def _gal_check() -> None:
    """模块导入时自检银道系。

    只认「可交叉验证的实测锚点」，不认公式形态——因为公式形态很容易自我一致
    却整体错位（历史缺陷：矩阵转置存放，银心仍然对得上，但银经整体偏 113°，
    只有拿真实恒星的银经去比才能发现）。

    锚点一：本程序算出的矩阵必须等于 PAL/SLALib ``eqgal.f`` 的官方 IAU 1958
            矩阵（J2000，Blaauw et al. 1960），逐元素误差 < 1e-5。
    锚点二：几颗亮星的 (银经, 银纬) 必须与天文年历值一致（误差 < 0.1°）：
            天狼  227.23 / −8.89      织女一  67.45 / +19.24
            大角   15.05 / +69.11     参宿四 199.79 / −8.96
            老人  261.21 / −25.29     银心    0.00 / 0.00
    """
    official = (
        (-0.054875539726, -0.873437108010, -0.483834985808),
        (+0.494109453312, -0.444829589425, +0.746982251810),
        (-0.867666135858, -0.198076386122, +0.455983795705),
    )
    worst = max(abs(_GAL_MATRIX[i][j] - official[i][j])
                for i in range(3) for j in range(3))
    if worst > 1e-5:
        raise RuntimeError(f"银道系自检失败：旋转矩阵与 PAL 官方值偏差 {worst:.2e}")

    anchors = (
        (101.2872, -16.7161, 227.230, -8.890, "天狼"),
        (279.2347, 38.7837, 67.448, 19.237, "织女一"),
        (213.9153, 19.1824, 15.050, 69.111, "大角"),
        (88.7929, 7.4071, 199.787, -8.959, "参宿四"),
        (95.9880, -52.6957, 261.212, -25.292, "老人"),
        (266.4051, -28.9362, 0.000, 0.000, "银心"),
    )
    for ra, dec, want_l, want_b, name in anchors:
        got_l = galactic_longitude(ra, dec)
        got_b = galactic_latitude(ra, dec)
        dl = abs((got_l - want_l + 180.0) % 360.0 - 180.0)
        if dl > 0.1 or abs(got_b - want_b) > 0.1:
            raise RuntimeError(f"银道系自检失败：{name} 的银道坐标为 "
                               f"l={got_l:.3f} b={got_b:+.3f}，应为 l={want_l:.3f} b={want_b:+.3f}")

    # 银道 → 赤道 → 银道 必须闭合（容差 1e-5：两根基轴取自实测常数，只精确到
    # 小数第五位左右，矩阵与严格正交差约 1e-6，往返不可能闭合到 1e-9）
    for l, b in ((0.0, 0.0), (123.0, 45.0), (300.0, -60.0)):
        v_gal = (math.cos(b * D2R) * math.cos(l * D2R),
                 math.cos(b * D2R) * math.sin(l * D2R),
                 math.sin(b * D2R))
        v_eq = galactic_to_equatorial_vec(v_gal, inverse=False)
        back = galactic_to_equatorial_vec(v_eq, inverse=True)
        if max(abs(back[i] - v_gal[i]) for i in range(3)) > 1e-5:
            raise RuntimeError(f"银道系自检失败：往返换算不闭合（l={l}, b={b}）")


def galactic_to_equatorial(l_deg: float, b_deg: float) -> Tuple[float, float]:
    """银道坐标（银经 l、银纬 b）→ J2000 赤道坐标（赤经、赤纬）。

    使用显式构造的旋转矩阵 _GAL_MATRIX（行 = 银道基轴的赤道分量），
    v_eq = R · v_gal，其中 v_gal 是银道系中的单位向量。
    校验：l=0,b=0   → 银心 ra ≈ 266.40°, dec ≈ -28.94°（人马座 A* 方向）
          l=0,b=90  → 银北极 ra ≈ 192.86°, dec ≈ 27.13°
          l=90,b=0  → ra ≈ 318.0°, dec ≈ -48.9°（银道面赤纬最低处）
    """
    l, b = l_deg * D2R, b_deg * D2R
    vx = math.cos(b) * math.cos(l)
    vy = math.cos(b) * math.sin(l)
    vz = math.sin(b)
    row_x, row_y, row_z = _GAL_MATRIX
    # v_eq = Rᵀ · v_gal：对第 j 个赤道分量，取三根基轴的第 j 个分量加权求和
    return vec_to_radec((
        row_x[0] * vx + row_y[0] * vy + row_z[0] * vz,
        row_x[1] * vx + row_y[1] * vy + row_z[1] * vz,
        row_x[2] * vx + row_y[2] * vy + row_z[2] * vz,
    ))


def galactic_latitude(ra_deg: float, dec_deg: float) -> float:
    """给定赤道坐标，返回其银纬（度）。

    用途：判断某个天体是否落在银河带上（|b| < 10° 视为银河带内），
    也用于「银河带」图层的自检。
    实现：天体单位向量与银北极方向（_GAL_MATRIX 第 2 行）点乘后取反正弦。
    """
    v = radec_to_vec(ra_deg, dec_deg)
    nz = _GAL_MATRIX[2]
    return math.degrees(math.asin(clamp(nz[0] * v[0] + nz[1] * v[1] + nz[2] * v[2], -1.0, 1.0)))


def galactic_longitude(ra_deg: float, dec_deg: float) -> float:
    """给定赤道坐标，返回其银经（度，0~360）。

    实现：天体单位向量分别与银心方向（_GAL_MATRIX 第 0 行，即 l=0）和
    银道系 y 轴（第 1 行，即 l=90）点乘，两分量取 atan2。
    """
    v = radec_to_vec(ra_deg, dec_deg)
    nx, ny = _GAL_MATRIX[0], _GAL_MATRIX[1]
    gx = nx[0] * v[0] + nx[1] * v[1] + nx[2] * v[2]
    gy = ny[0] * v[0] + ny[1] * v[1] + ny[2] * v[2]
    return norm360(math.degrees(math.atan2(gy, gx)))


def equatorial_vector_to_galactic(v: Sequence[float]) -> Tuple[float, float, float]:
    """赤道直角向量 → 银道直角向量（保持长度）：v_gal = R · v_eq。"""
    return (galactic_to_equatorial_vec(v, inverse=True))


def galactic_to_equatorial_vec(v: Sequence[float], inverse: bool = False) -> Tuple[float, float, float]:
    """银道 / 赤道直角向量互转（保留原始长度，非单位向量也可）。

    inverse=False：v_eq  = Rᵀ · v_gal（银道 → 赤道）
    inverse=True ：v_gal = R  · v_eq（赤道 → 银道）
    """
    row_x, row_y, row_z = _GAL_MATRIX
    if inverse:
        return (row_x[0] * v[0] + row_x[1] * v[1] + row_x[2] * v[2],
                row_y[0] * v[0] + row_y[1] * v[1] + row_y[2] * v[2],
                row_z[0] * v[0] + row_z[1] * v[1] + row_z[2] * v[2])
    return (row_x[0] * v[0] + row_y[0] * v[1] + row_z[0] * v[2],
            row_x[1] * v[0] + row_y[1] * v[1] + row_z[1] * v[2],
            row_x[2] * v[0] + row_y[2] * v[1] + row_z[2] * v[2])


def galactic_vector_to_equatorial(v: Sequence[float]) -> Tuple[float, float, float]:
    """银道直角向量 → 赤道直角向量（equatorial_vector_to_galactic 的逆）。"""
    return galactic_to_equatorial_vec(v, inverse=False)


def equatorial_to_horizontal(ra_deg: float, dec_deg: float, lst_deg: float,
                             lat_deg: float) -> Tuple[float, float]:
    """赤道坐标 → 地平坐标（高度角, 方位角），单位度。

    时角 H = 地方恒星时 - 赤经
    高度角 h = asin(sinφ·sinδ + cosφ·cosδ·cosH)
    方位角 A = atan2(-cosδ·sinH, sinδ·cosφ - cosδ·sinφ·cosH) 后归一到 [0,360)
    """
    try:
        h = (lst_deg - ra_deg) * D2R                     # 时角（弧度）
        dec = dec_deg * D2R
        lat = lat_deg * D2R
        sin_alt = math.sin(lat) * math.sin(dec) + math.cos(lat) * math.cos(dec) * math.cos(h)
        alt = math.asin(clamp(sin_alt, -1.0, 1.0))
        az = math.atan2(-math.cos(dec) * math.sin(h),
                        math.sin(dec) * math.cos(lat) - math.cos(dec) * math.sin(lat) * math.cos(h))
        return (alt * R2D, norm360(az * R2D))
    except Exception:
        return (0.0, 0.0)


def horizontal_to_equatorial(alt_deg: float, az_deg: float, lst_deg: float,
                             lat_deg: float) -> Tuple[float, float]:
    """地平坐标 → 赤道坐标（逆变换，供「点击天空反查坐标」使用）。"""
    alt, az = alt_deg * D2R, az_deg * D2R
    lat = lat_deg * D2R
    sin_dec = math.sin(alt) * math.sin(lat) + math.cos(alt) * math.cos(lat) * math.cos(az)
    dec = math.asin(clamp(sin_dec, -1.0, 1.0))
    h = math.atan2(-math.cos(alt) * math.sin(az),
                   math.sin(alt) * math.cos(lat) - math.cos(alt) * math.sin(lat) * math.cos(az))
    ra = norm360(lst_deg - h * R2D)
    return (ra, dec * R2D)


def altaz_to_vector(alt_deg: float, az_deg: float) -> Tuple[float, float, float]:
    """地平坐标 → 观测者本地单位向量（右手系：X=东, Y=北, Z=天顶）。

    这是渲染层的核心：把天体位置变成三维方向向量后，投影只需要做旋转 + 透视。
    """
    alt, az = alt_deg * D2R, az_deg * D2R
    ca = math.cos(alt)
    return (ca * math.sin(az),      # 东
            ca * math.cos(az),      # 北
            math.sin(alt))          # 天顶


def apply_refraction(alt_deg: float, pressure_hpa: float = 1010.0,
                     temp_c: float = 10.0) -> float:
    """大气折射修正（Saemundsson 公式），返回视高度角。

    靠近地平线的天体看起来会更「高」一点（地平线附近约 34′），
    这样渲染出来的地平线附近星空更接近肉眼观感。
    """
    if alt_deg < -1.5:
        return alt_deg
    try:
        r = 1.02 / math.tan((alt_deg + 10.3 / (alt_deg + 5.11)) * D2R)
        r *= (pressure_hpa / 1010.0) * (283.0 / (273.0 + temp_c)) / 60.0
        return alt_deg + r
    except Exception:
        return alt_deg


