# 七、地平视差修正（月亮/近距行星）
# ==============================================================================

def topocentric_correction(ra_deg: float, dec_deg: float, dist_au: float,
                           lat_deg: float, lst_deg: float,
                           elevation_m: float = 0.0) -> Tuple[float, float]:
    """地心坐标 → 站心（地平视差）修正。

    对月亮影响最大（视差约 1°，必须修正），对行星影响极小但一并处理。
    """
    try:
        if dist_au <= 0 or dist_au > 1e4:
            return (ra_deg, dec_deg)
        sin_pi = EARTH_RADIUS_AU / dist_au          # 赤道地平视差
        if sin_pi < 1e-8:
            return (ra_deg, dec_deg)
        b = 0.99664719                              # 地球椭球短半轴/长半轴
        u = math.atan(b * math.tan(lat_deg * D2R))
        h = EARTH_RADIUS_AU * 0.0                   # 海拔项（以地球半径为单位，量级极小）
        rho_sin = b * math.sin(u) + h * math.sin(lat_deg * D2R)
        rho_cos = math.cos(u) + h * math.cos(lat_deg * D2R)
        h_ang = (lst_deg - ra_deg) * D2R
        dec = dec_deg * D2R
        d_ra = math.atan2(-rho_cos * sin_pi * math.sin(h_ang),
                          math.cos(dec) - rho_cos * sin_pi * math.cos(h_ang))
        dec_new = math.atan2((math.sin(dec) - rho_sin * sin_pi) * math.cos(d_ra),
                             math.cos(dec) - rho_cos * sin_pi * math.cos(h_ang))
        return (norm360(ra_deg + d_ra * R2D), dec_new * R2D)
    except Exception:
        return (ra_deg, dec_deg)


