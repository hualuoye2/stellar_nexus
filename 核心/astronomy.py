def moon_position(jd: float) -> Dict[str, float]:
    """月亮的地心位置（Meeus 第 47 章，完整 60+60 项级数）。

    入参 jd 为**世界时**儒略日，函数内部换算到力学时（TT）。
    这一步不是可选项：月亮每秒走 0.549″，ΔT 在 2026 年约 75 秒，
    不换算就是 41″ 的系统偏差。实测（对权威月相表）：
        不换算 → 合朔时刻平均偏差 +2.24 分钟（最大 +2.82）
        换算后 → 平均偏差 +0.98 分钟（最大 +1.56）
    校验：tools/check_moon_accuracy.py

    返回：ra / dec（度）、lon / lat（黄经黄纬）、distance（公里）、phase（0~1 月相）
    """
    jd = jd_tt(jd)
    t = julian_centuries(jd)
    # --- 1) 基本角度 ---
    lp = norm360(218.3164477 + 481267.88123421 * t - 0.0015786 * t ** 2
                 + t ** 3 / 538841.0 - t ** 4 / 65194000.0)          # 平黄经
    d = norm360(297.8501921 + 445267.1114034 * t - 0.0018819 * t ** 2
                + t ** 3 / 545868.0 - t ** 4 / 113065000.0)          # 平距角
    m = norm360(357.5291092 + 35999.0502909 * t - 0.0001536 * t ** 2
                + t ** 3 / 24490000.0)                               # 太阳平近点角
    mp = norm360(134.9633964 + 477198.8675055 * t + 0.0087414 * t ** 2
                 + t ** 3 / 69699.0 - t ** 4 / 14712000.0)           # 月亮平近点角
    f = norm360(93.2720950 + 483202.0175233 * t - 0.0036539 * t ** 2
                - t ** 3 / 3526000.0 + t ** 4 / 863310000.0)         # 纬度参数
    a1 = norm360(119.75 + 131.849 * t)
    a2 = norm360(53.09 + 479264.290 * t)
    a3 = norm360(313.45 + 481266.484 * t)
    e = 1.0 - 0.002516 * t - 0.0000074 * t * t   # 地球轨道偏心率修正
    # --- 2) 求和 ---
    sum_l = 0.0
    sum_r = 0.0
    for cd, cm, cmp_, cf, cl, cr in _MOON_LR_TERMS:
        arg = (cd * d + cm * m + cmp_ * mp + cf * f) * D2R
        ecc = e ** abs(cm)
        sum_l += cl * ecc * math.sin(arg)
        if cr:
            sum_r += cr * ecc * math.cos(arg)
    sum_b = 0.0
    for cd, cm, cmp_, cf, cb in _MOON_B_TERMS:
        arg = (cd * d + cm * m + cmp_ * mp + cf * f) * D2R
        sum_b += cb * (e ** abs(cm)) * math.sin(arg)
    # --- 3) 附加项（金星/木星摄动、扁率项） ---
    sum_l += 3958.0 * math.sin(a1 * D2R) + 1962.0 * math.sin((lp - f) * D2R) \
        + 318.0 * math.sin(a2 * D2R)
    sum_b += (-2235.0 * math.sin(lp * D2R) + 382.0 * math.sin(a3 * D2R)
              + 175.0 * math.sin((a1 - f) * D2R) + 175.0 * math.sin((a1 + f) * D2R)
              + 127.0 * math.sin((lp - mp) * D2R) - 115.0 * math.sin((lp + mp) * D2R))
    # --- 4) 黄经/黄纬/距离 ---
    lon = norm360(lp + sum_l / 1e6)
    lat = sum_b / 1e6
    dist_km = 385000.56 + sum_r / 1000.0
    ra, dec = ecliptic_to_equatorial(lon, lat, jd)
    # --- 5) 月相（0=新月, 0.5=满月）：用月亮与太阳的黄经差 ---
    sun = sun_position(jd)
    elong = norm360(lon - sun["lon"])
    phase = 0.5 * (1.0 - math.cos(elong * D2R))  # 照亮比例
    return {"ra": ra, "dec": dec, "lon": lon, "lat": lat, "distance": dist_km,
            "distance_au": dist_km / AU_KM, "phase": phase, "elongation": elong,
            "name": "月球"}


def moon_phase_name(phase: float) -> str:
    """照亮比例 → 中文月相名称。"""
    p = clamp(float(phase), 0.0, 1.0)
    if p < 0.03:
        return "新月"
    if p < 0.35:
        return "蛾眉月" if p > 0.03 else "新月"
    if p < 0.47:
        return "上弦月"
    if p < 0.53:
        return "上弦月" if p < 0.5 else "盈凸月"
    if p < 0.65:
        return "盈凸月"
    if p < 0.97:
        return "满月" if p > 0.93 else "亏凸月"
    return "满月"


