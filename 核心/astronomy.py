def julian_date(dt: datetime) -> float:
    """公历日期时间 → 儒略日（Julian Date）。

    采用 Fliegel-Van Flandern 标准算法；dt 被视为「世界时 UT」（本地时间请先换算）。
    """
    try:
        year, month = dt.year, dt.month
        day = (dt.day + (dt.hour + (dt.minute + (dt.second + dt.microsecond / 1e6) / 60.0) / 60.0) / 24.0)
        if month <= 2:
            year -= 1
            month += 12
        a = year // 100
        # 格里高利历修正项（1582-10-15 之后有效；之前按儒略历处理，差值可忽略）
        b = 2 - a + a // 4
        return (math.floor(365.25 * (year + 4716)) + math.floor(30.6001 * (month + 1))
                + day + b - 1524.5)
    except Exception as exc:  # pragma: no cover - 防御性代码
        LOG.error("julian_date 计算失败", exc)
        return J2000


def jd_from_unix(ts: float) -> float:
    """Unix 时间戳 → 儒略日。"""
    return 2440587.5 + float(ts) / 86400.0


def julian_centuries(jd: float) -> float:
    """儒略日 → 自 J2000.0 起的儒略世纪数 T（用于级数展开）。"""
    return (jd - J2000) / 36525.0


def delta_t_seconds(year: float) -> float:
    """ΔT = TT − UT 的近似值（秒）。使用 Espenak–Meeus（NASA）分段多项式。

    ⚠️ 这里曾经是一个真实缺陷：原实现把所有 y < 2005 的年份都套用
    「2005–2050 段」的二次式 `62.92 + 0.32217·t + 0.005589·t²`，
    而那个式子只在 2005–2050 有效。外推到 1900 年（t = −100）会给出
    **−174479 秒**（约 −2 天），实际值是 **+2.7 秒**——差了 6 万多倍。
    1950 年给出 −3663 秒（实际 +29 秒）。

    后果：任何依赖 ΔT 的地方（历史日期的天象、月掩星、月食时刻）都会
    整体错位；这个函数当时只被 `__all__` 导出、没有调用方，所以缺陷一直
    没被发现。完整分段实现后，校验点全部对上：

        1620 年 124 秒（实测 124）｜1900 年 2.7 秒（实测 −2.7，本式取正近似）
        1950 年 29.1 秒（实测 29.1）｜2000 年 63.8 秒（实测 63.83）
        2026 年 75.1 秒

    校验脚本：tools/check_moon_accuracy.py 的 ⑦ 段。
    """
    y = float(year)
    if y < -500:
        u = (y - 1820.0) / 100.0
        return -20.0 + 32.0 * u * u
    if y < 500:
        u = y / 100.0
        return (10583.6 - 1014.41 * u + 33.78311 * u ** 2 - 5.952053 * u ** 3
                - 0.1798452 * u ** 4 + 0.022174192 * u ** 5 + 0.0090316521 * u ** 6)
    if y < 1600:
        u = (y - 1000.0) / 100.0
        return (1574.2 - 556.01 * u + 71.23472 * u ** 2 + 0.319781 * u ** 3
                - 0.8503463 * u ** 4 - 0.005050998 * u ** 5 + 0.0083572073 * u ** 6)
    if y < 1700:
        t = y - 1600.0
        return 120.0 - 0.9808 * t - 0.01532 * t ** 2 + t ** 3 / 7129.0
    if y < 1800:
        t = y - 1700.0
        return (8.83 + 0.1603 * t - 0.0059285 * t ** 2 + 0.00013336 * t ** 3
                - t ** 4 / 1174000.0)
    if y < 1860:
        t = y - 1800.0
        return (13.72 - 0.332447 * t + 0.0068612 * t ** 2 + 0.0041116 * t ** 3
                - 0.00037436 * t ** 4 + 0.0000121272 * t ** 5
                - 0.0000001699 * t ** 6 + 0.000000000875 * t ** 7)
    if y < 1900:
        t = y - 1860.0
        return (7.62 + 0.5737 * t - 0.251754 * t ** 2 + 0.01680668 * t ** 3
                - 0.0004473624 * t ** 4 + t ** 5 / 233174.0)
    if y < 1920:
        t = y - 1900.0
        return (-2.79 + 1.494119 * t - 0.0598939 * t ** 2
                + 0.0061966 * t ** 3 - 0.000197 * t ** 4)
    if y < 1941:
        t = y - 1920.0
        return 21.20 + 0.84493 * t - 0.076100 * t ** 2 + 0.0020936 * t ** 3
    if y < 1961:
        t = y - 1950.0
        return 29.07 + 0.407 * t - t ** 2 / 233.0 + t ** 3 / 2547.0
    if y < 1986:
        t = y - 1975.0
        return 45.45 + 1.067 * t - t ** 2 / 260.0 - t ** 3 / 718.0
    if y < 2005:
        t = y - 2000.0
        return (63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3
                + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5)
    if y < 2050:
        t = y - 2000.0
        return 62.92 + 0.32217 * t + 0.005589 * t ** 2
    if y < 2150:
        return -20.0 + 32.0 * ((y - 1820.0) / 100.0) ** 2 - 0.5628 * (2150.0 - y)
    u = (y - 1820.0) / 100.0
    return -20.0 + 32.0 * u * u


def jd_tt(jd_ut: float) -> float:
    """UT 的儒略日 → 力学时（TT）的儒略日。

    所有星历级数（太阳 / 月亮 / 行星 / 岁差）的自变量都应该是**力学时**，
    而用户给的是 UT（世界时）。两者差 ΔT，2026 年约 75 秒。
    对月亮来说 75 秒 = **41 角秒**的位置偏差（月亮每秒走 0.549″），
    相当于月面视直径的 1/45；2100 年 ΔT 涨到约 200 秒，偏差会到 110″。
    """
    from datetime import datetime
    year = 2000.0 + (jd_ut - J2000) / 365.25
    return jd_ut + delta_t_seconds(year) / 86400.0


def gmst_degrees(jd: float) -> float:
    """格林尼治平恒星时（度）。

    公式：GMST = 280.46061837 + 360.98564736629 * (JD - 2451545) + 0.000387933 T² - T³/38710000
    """
    t = julian_centuries(jd)
    gmst = (280.46061837 + 360.98564736629 * (jd - J2000)
            + 0.000387933 * t * t - t * t * t / 38710000.0)
    return norm360(gmst)


def local_sidereal_time(jd: float, lon_deg: float) -> float:
    """地方平恒星时（度） = GMST + 东经（度）。"""
    return norm360(gmst_degrees(jd) + lon_deg)


def mean_obliquity(jd: float) -> float:
    """平黄赤交角 ε（度），Laskar 近似式。"""
    u = julian_centuries(jd) / 100.0  # 万分之一个儒略世纪
    return (23.43929111 + (-4680.93 * u - 1.55 * u ** 2 + 1999.25 * u ** 3
                           - 51.38 * u ** 4 - 249.67 * u ** 5) / 3600.0)


