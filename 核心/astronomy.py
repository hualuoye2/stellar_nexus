@dataclass
class SkyObject:
    """一个可以在星图上渲染/点击的天体（恒星、行星、太阳、月亮、深空天体）。"""

    key: str = ""
    name: str = ""
    name_en: str = ""
    name_cn: str = ""           # 中文常用名（深空天体使用，恒星留空）
    kind: str = "star"          # star / planet / sun / moon / messier / constellation
    ra: float = 0.0
    dec: float = 0.0
    alt: float = -90.0
    az: float = 0.0
    mag: float = 6.0
    bv: float = 0.65
    spectral: str = ""
    distance: Optional[float] = None      # 光年（恒星）/ 天文单位（行星）
    constellation: str = ""
    extra: Dict[str, object] = field(default_factory=dict)

    @property
    def visible(self) -> bool:
        """是否在地平线以上。"""
        return self.alt > 0.0


def compute_sky(observer: Observer,
                star_catalog: Sequence[object],
                planets: Sequence[str] = ("mercury", "venus", "mars", "jupiter", "saturn"),
                messier: Sequence[object] = (),
                include_sun_moon: bool = True,
                include_below_horizon: bool = True) -> Dict[str, List[SkyObject]]:
    """一次性算出当前天空的所有天体位置。

    参数：
        observer      观测者（含时间、经纬度）
        star_catalog  恒星对象序列（需要 ra / dec / mag / bv / name 等属性）
        planets       需要计算的行星键名
        messier       深空天体序列（Messier / NGC / IC）
        include_sun_moon 是否计算太阳与月亮
        include_below_horizon
                      是否把**地平线以下**的天体也计算出来。
                      True（默认）：返回整个天球，渲染层再按图层开关决定是否绘制
                      地下部分——这样用户可以查看"现在看不到、几点会升起"的目标；
                      False：只返回地平线以上（含少量折射余量）的目标，省一点算力。

    返回：{"stars": [...], "planets": [...], "deep_sky": [...], "sun_moon": [...]}
    """
    lst = observer.lst
    lat = observer.lat
    out: Dict[str, List[SkyObject]] = {"stars": [], "planets": [], "deep_sky": [], "sun_moon": []}
    # 地平线以下天体保留到多低：-92° 表示整个天球都保留
    alt_floor = -92.0 if include_below_horizon else -2.0

    # ---- 恒星（J2000 坐标 → 岁差 → 地平） ----
    jd = observer.jd_ut
    try:
        for st in star_catalog:
            ra, dec = precess(getattr(st, "ra", 0.0), getattr(st, "dec", 0.0), J2000, jd)
            alt, az = equatorial_to_horizontal(ra, dec, lst, lat)
            out["stars"].append(SkyObject(
                key=f"star:{getattr(st, 'hip', 0)}",
                name=getattr(st, "name", ""), name_en=getattr(st, "name_en", ""),
                kind="star", ra=ra, dec=dec, alt=alt, az=az,
                mag=float(getattr(st, "mag", 6.0)), bv=float(getattr(st, "bv", 0.65)),
                spectral=getattr(st, "spectral", ""),
                distance=getattr(st, "distance", None),
                constellation=getattr(st, "constellation", ""),
                extra={"hip": getattr(st, "hip", 0), "bayer": getattr(st, "bayer", "")},
            ))
    except Exception as exc:
        LOG.error("恒星位置计算失败", exc)

    # ---- 太阳 & 月球 ----
    if include_sun_moon:
        try:
            sun = sun_position(jd)
            alt, az = equatorial_to_horizontal(sun["ra"], sun["dec"], lst, lat)
            out["sun_moon"].append(SkyObject(
                key="sun", name="太阳", name_en="Sun", kind="sun",
                ra=sun["ra"], dec=sun["dec"], alt=alt, az=az, mag=-26.74, bv=0.65,
                distance=sun["distance"], spectral="G2V",
                extra={"distance_km": sun["distance"] * AU_KM},
            ))
            moon = moon_position(jd)
            mra, mdec = topocentric_correction(moon["ra"], moon["dec"],
                                               moon["distance_au"], lat, lst, observer.elevation_m)
            alt, az = equatorial_to_horizontal(mra, mdec, lst, lat)
            out["sun_moon"].append(SkyObject(
                key="moon", name="月球", name_en="Moon", kind="moon",
                ra=mra, dec=mdec, alt=alt, az=az, mag=-12.7 + 0.026 * abs(moon["phase"] * 100 - 50),
                bv=0.6, distance=moon["distance_au"], spectral="G2V",
                extra={"phase": moon["phase"], "phase_name": moon_phase_name(moon["phase"]),
                       "distance_km": moon["distance"], "elongation": moon["elongation"]},
            ))
        except Exception as exc:
            LOG.error("太阳/月亮位置计算失败", exc)

    # ---- 行星 ----
    try:
        for key in planets:
            p = planet_position(key, jd)
            ra, dec = topocentric_correction(p["ra"], p["dec"], p["distance"], lat, lst)
            alt, az = equatorial_to_horizontal(ra, dec, lst, lat)
            # 视星等的粗略近似（几何反照率简化模型，足够展示）
            out["planets"].append(SkyObject(
                key=f"planet:{key}", name=p["name"], name_en=p.get("name_en", key), kind="planet",
                ra=ra, dec=dec, alt=alt, az=az,
                mag=_approx_planet_mag(key, p["distance"]),
                bv=_planet_bv(key), distance=p["distance"],
                extra={"heliocentric_lon": p["lon"], "heliocentric_lat": p["lat"]},
            ))
    except Exception as exc:
        LOG.error("行星位置计算失败", exc)

    # ---- 深空天体（Messier / NGC / IC） ----
    try:
        for m in messier:
            ra, dec = precess(getattr(m, "ra", 0.0), getattr(m, "dec", 0.0), J2000, jd)
            alt, az = equatorial_to_horizontal(ra, dec, lst, lat)
            out["deep_sky"].append(SkyObject(
                key=f"messier:{getattr(m, 'name', '')}",
                name=getattr(m, "name", ""), name_en=getattr(m, "name_en", ""),
                name_cn=getattr(m, "name_cn", ""),
                kind="messier", ra=ra, dec=dec, alt=alt, az=az,
                mag=float(getattr(m, "mag", 8.0)), bv=0.6,
                constellation=getattr(m, "constellation", ""),
                extra={"mtype": getattr(m, "mtype", ""), "size": getattr(m, "size", ""),
                       "desc": getattr(m, "desc", "")},
            ))
    except Exception as exc:
        LOG.error("深空天体位置计算失败", exc)

    return out


#: 行星视星等基准（对应 r = 1AU、Δ = 1AU、相位角 0°）
_PLANET_MAG_BASE = {"mercury": -0.42, "venus": -4.40, "mars": -1.52,
                    "jupiter": -9.40, "saturn": -8.88, "uranus": -7.19, "neptune": -6.87}


def _approx_planet_mag(planet: str, dist_au: float) -> float:
    """按地心距快速估算行星亮度：V ≈ V0 + 5·log10(Δ) + 5·log10(r̄)。

    精确计算（含相位角）由 planet_data.approximate_magnitude() 提供；
    这里使用各行星的平均日心距 r̄，避免在 compute_sky() 中重复求解轨道。
    """
    base = _PLANET_MAG_BASE.get(planet, 5.0)
    mean_r = {"mercury": 0.387, "venus": 0.723, "mars": 1.524, "jupiter": 5.203,
              "saturn": 9.537, "uranus": 19.19, "neptune": 30.07}.get(planet, 1.0)
    try:
        delta = max(0.05, float(dist_au))
        return base + 5.0 * math.log10(delta * mean_r)
    except Exception:
        return base


def _planet_bv(planet: str) -> float:
    """行星的近似 B-V 色指数（用于渲染配色）。"""
    return {"mercury": 0.75, "venus": 0.6, "mars": 1.35, "jupiter": 0.83,
            "saturn": 0.9, "uranus": 0.55, "neptune": 0.5}.get(planet, 0.7)


