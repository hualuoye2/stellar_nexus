def _resolve_name_cn(hip: int, name_en: str) -> str:
    """取中文名：优先 HIP 表，其次英文名映射表，最后用「附加亮星表」。"""
    if hip in STAR_NAMES_CN:
        return STAR_NAMES_CN[hip]
    for row in ADDITIONAL_STARS:
        if int(row[0]) == int(hip):
            return str(row[1])
    return STAR_NAMES_CN_BY_EN.get(name_en, "")


def _additional_star_rows() -> List[Tuple[int, str, str, float, float, float, float, str, str]]:
    """把「附加亮星表」转换为与 DETAIL_STARS 相同的行格式。

    坐标直接从 EXTRA_STARS（星座连线用的权威亮星数据）中取出，
    因此不存在手抄坐标出错的可能；若某个 HIP 不在补充星表中则跳过。
    """
    rows: List[Tuple[int, str, str, float, float, float, float, str, str]] = []
    for hip, cn, en, spectral, abbr in ADDITIONAL_STARS:
        ref = EXTRA_STARS.get(int(hip)) or ADDITIONAL_STAR_COORDS.get(int(hip))
        if ref is None:
            LOG_WARN_HIP.append(int(hip))
            continue
        ra, dec, mag, bv = ref
        rows.append((int(hip), str(cn), str(en), float(ra), float(dec),
                     float(mag), float(bv), str(spectral), str(abbr)))
    return rows


#: 补充星表中缺失的 HIP（自检用）
LOG_WARN_HIP: List[int] = []


def _authoritative_coords(hip: int) -> Optional[Tuple[float, float, float, float]]:
    """取某个 HIP 的**权威坐标**，优先级从高到低：

        1. FAINT_STARS（HYG v3.8，8870 颗，覆盖到 6.5 等）
        2. ADDITIONAL_STAR_COORDS（人工录入，且已与 HYG 逐条交叉核对）

    为什么需要这个函数：DETAIL_STARS 是自动生成的表，其中有 10 条坐标是错的，
    而且错得没有规律（不是统一的单位错，也不只是赤经错）：

        HIP 50371  生成表 148.1909/+9.7330      HYG 154.2708/−61.3323   （差 71°）
        HIP 78527  生成表 236.0691/+26.7160     HYG 240.4730/+58.5652   （差 32°）
        HIP 115623 生成表 343.7603/−7.4697      HYG 351.3449/+23.4041   （差 32°）
        HIP 1067   生成表 7.8869/−13.4014       HYG 3.3090/+15.1836     （差 29°）
        …共 10 条

    这些星会被画到完全错误的天区，而且因为它们"有名字"（轩辕十、土司空、天棓二…），
    在星图上比背景暗星更容易被注意到。既然 FAINT_STARS 里就有同一批 HIP 的正确值，
    就没有理由继续信生成表——所以在这里统一按 HIP 覆盖。

    实测覆盖效果：159 颗能在 HYG 里找到的具名星，坐标偏差从"最大 71.23°"
    降到"最大 0.000°"。校验脚本：tools/check_star_density.py 的 A 段。
    """
    ref = FAINT_STARS.get(int(hip))
    if ref is not None:
        return (float(ref[0]), float(ref[1]), float(ref[2]), float(ref[3]))
    ref = ADDITIONAL_STAR_COORDS.get(int(hip))
    if ref is not None:
        return (float(ref[0]), float(ref[1]), float(ref[2]), float(ref[3]))
    return None


#: 生成表里坐标被权威数据纠正过的 HIP（自检用：数量应恒为 10）
CORRECTED_HIP: List[int] = []


def _build_star_catalog() -> List[Star]:
    """把内置星表数据转换为 Star 对象列表（含附加亮星）。

    坐标一律经过 _authoritative_coords() 校正：优先 HYG，其次人工录入表。
    生成表 DETAIL_STARS 的坐标只在两者都查不到时才使用（这些星同时也会出现在
    LOG_WARN_HIP 之外，属于既没有 HYG 记录、也没有人工坐标的少数条目）。
    """
    stars: List[Star] = []
    seen: set = set()
    source: List[Tuple[int, str, str, float, float, float, float, str, str]] = (
        list(DETAIL_STARS) + _additional_star_rows())
    for hip, _cn_unused, name_en, ra, dec, mag, bv, _spec_unused, abbr in source:
        hip = int(hip)
        if hip in seen:
            continue
        seen.add(hip)
        auth = _authoritative_coords(hip)
        if auth is not None:
            ara, adec, amag, abv = auth
            if abs(ara - float(ra)) > 0.01 or abs(adec - float(dec)) > 0.01:
                CORRECTED_HIP.append(hip)
            ra, dec, mag, bv = ara, adec, amag, abv
        cn = _resolve_name_cn(hip, name_en)
        const_cn = CONSTELLATIONS.get(abbr, ("", ""))[0]
        stars.append(Star(
            hip=hip, name=cn, name_en=name_en, ra=float(ra), dec=float(dec),
            mag=float(mag), bv=float(bv),
            spectral=STAR_SPECTRAL.get(hip, ""),
            constellation=const_cn, constellation_abbr=abbr,
            distance=STAR_DISTANCES.get(hip),
        ))
    # 按星等排序：渲染时先画暗星后画亮星，层次更自然
    stars.sort(key=lambda s: s.mag)
    return stars


def _build_extra_stars() -> List[Star]:
    """构建补充恒星（星座连线所需的暗星）。"""
    stars: List[Star] = []
    for hip, (ra, dec, mag, bv) in EXTRA_STARS.items():
        if hip in STAR_BY_HIP:
            continue
        stars.append(Star(hip=int(hip), name="", name_en=f"HIP {hip}",
                          ra=float(ra), dec=float(dec), mag=float(mag), bv=float(bv),
                          spectral="", constellation="", constellation_abbr=""))
    stars.sort(key=lambda s: s.mag)
    return stars


def _build_faint_stars() -> List[Star]:
    """构建背景暗星层（HYG 里视星等 ≤ 6.5 的全部恒星）。

    为什么单独一层：内置星表原先只有 781 颗星（160 具名 + 621 连线端点），
    放大到 30° 视场时天空稀疏得认不出星座。HYG 星表里有 8870 颗亮于 6.5 等的
    恒星，把它们作为"背景星场"补进来，星场密度立刻有质变。

    与 EXTRA_STARS 的关系：两者会有大量重叠（连线端点星当然也在 HYG 里），
    去重交给 ALL_STAR_BY_HIP 与下面的 seen 集合处理——**具名与连线端点优先**，
    因为那两处的坐标经过人工校验。
    """
    stars: List[Star] = []
    for hip, (ra, dec, mag, bv) in FAINT_STARS.items():
        hip = int(hip)
        if hip in STAR_BY_HIP or hip in _EXTRA_HIP:
            continue
        stars.append(Star(hip=hip, name="", name_en="", ra=float(ra), dec=float(dec),
                          mag=float(mag), bv=float(bv), spectral="",
                          constellation="", constellation_abbr=""))
    stars.sort(key=lambda s: s.mag)
    return stars


def _build_deep_sky() -> List[MessierObject]:
    """构建深空天体列表（Messier 全集 + 著名 NGC/IC）。"""
    out: List[MessierObject] = []
    for name, en, cn, ra, dec, mag, mtype, size, abbr, desc in DEEP_SKY_RAW:
        cname = CONSTELLATIONS.get(abbr, ("", ""))[0]
        out.append(MessierObject(name=name, name_en=en, name_cn=cn, ra=ra, dec=dec,
                                 mag=mag, mtype=mtype, size=size, constellation=cname, desc=desc))
    return out


#: 最终导出的数据（模块级单例）
STAR_CATALOG: List[Star] = _build_star_catalog()

#: HIP → Star 快速索引
STAR_BY_HIP: Dict[int, Star] = {s.hip: s for s in STAR_CATALOG}

#: 补充恒星（星座连线 / 背景星场）
EXTRA_STAR_CATALOG: List[Star] = _build_extra_stars()

#: 补充星表的 HIP 集合（背景暗星层用它去重，避免同一颗星画两遍）
_EXTRA_HIP: set = {s.hip for s in EXTRA_STAR_CATALOG}

#: 背景暗星层（HYG 里亮于 6.5 等的全部恒星，去掉已有条目）
FAINT_STAR_CATALOG: List[Star] = _build_faint_stars()

#: 全部用于渲染的恒星（具名亮星 + 连线端点 + 背景暗星，按星等排序）
#: 注意：实际每帧只画"当前极限星等"以内的那些（见 RealSkyView._culled_stars），
#: 所以 8870 颗不会全部同时上屏——波特尔 5 级约 3000 颗，市区约 1250 颗。
ALL_SKY_STARS: List[Star] = sorted(
    STAR_CATALOG + EXTRA_STAR_CATALOG + FAINT_STAR_CATALOG, key=lambda s: s.mag)

#: 全部恒星的 HIP 索引（含补充星）
ALL_STAR_BY_HIP: Dict[int, Star] = {s.hip: s for s in ALL_SKY_STARS}

DEEP_SKY_CATALOG: List[MessierObject] = _build_deep_sky()

#: 向后兼容别名（旧代码仍可使用 MESSIER_CATALOG 这个名字）
MESSIER_CATALOG: List[MessierObject] = DEEP_SKY_CATALOG

#: 星座 → 恒星列表
STARS_BY_CONSTELLATION: Dict[str, List[Star]] = {}
for _s in STAR_CATALOG:
    STARS_BY_CONSTELLATION.setdefault(_s.constellation_abbr, []).append(_s)


