def milky_way_points(step_deg: float = 6.0, b_max: float = 11.0) -> List[Tuple[List[float], List[float]]]:
    """生成银河带的多条「银纬圈」采样点（J2000 赤道坐标）。

    为了让银河看起来有宽度和层次，这里取 b = 0, ±4°, ±8° 共 5 条带，
    调用方按银纬把亮度做衰减即可画出柔和的银河光带。

    注意：这只是"几何骨架"。真实银河的表面亮度沿银经变化极大
    （银心比反银心亮 3~5 倍）并且有大暗带，那部分见 milky_way_brightness()
    与 milky_way_rift_lanes()。
    """
    bands: List[Tuple[List[float], List[float]]] = []
    try:
        for b in (0.0, 4.0, -4.0, 8.0, -8.0, b_max, -b_max):
            ras: List[float] = []
            decs: List[float] = []
            l = 0.0
            while l <= 360.0:
                ra, dec = galactic_to_equatorial(l, b)
                ras.append(ra)
                decs.append(dec)
                l += step_deg
            bands.append((ras, decs))
    except Exception as exc:
        LOG.error("银河带采样失败", exc)
    return bands


