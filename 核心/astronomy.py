def sun_position(jd: float) -> Dict[str, float]:
    """太阳的地心位置。入参 jd 为**世界时**儒略日，函数内部自动换算到力学时。

    返回字典包含：
        ra / dec    视赤经、视赤纬（度）
        lon / lat   黄经、黄纬（度）
        distance    日地距离（天文单位）
        R           同上（兼容写法）
    """
    jd = jd_tt(jd)
    t = julian_centuries(jd)
    # 1) 几何平黄经与平近点角
    l0 = norm360(280.46646 + 36000.76983 * t + 0.0003032 * t * t)
    m = norm360(357.52911 + 35999.05029 * t - 0.0001537 * t * t)
    e = 0.016708634 - 0.000042037 * t - 0.0000001267 * t * t
    m_r = m * D2R
    # 2) 中心差（方程中心）
    c = ((1.914602 - 0.004817 * t - 0.000014 * t * t) * math.sin(m_r)
         + (0.019993 - 0.000101 * t) * math.sin(2 * m_r)
         + 0.000289 * math.sin(3 * m_r))
    true_lon = l0 + c
    true_anom = m + c
    # 3) 日地距离
    r = (1.000001018 * (1 - e * e)) / (1 + e * math.cos(true_anom * D2R))
    # 4) 视黄经（含章动与光行差）
    omega = 125.04 - 1934.136 * t
    app_lon = true_lon - 0.00569 - 0.00478 * math.sin(omega * D2R)
    # 5) 转赤道坐标（黄纬取 0，太阳黄纬极小于 1″）
    ra, dec = ecliptic_to_equatorial(app_lon, 0.0, jd)
    return {"ra": ra, "dec": dec, "lon": norm360(app_lon), "lat": 0.0,
            "distance": r, "R": r, "true_lon": norm360(true_lon), "name": "太阳"}


