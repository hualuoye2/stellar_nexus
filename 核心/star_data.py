def get_star(hip: int) -> Optional[Star]:
    """按 HIP 编号取星（含补充星）。"""
    return ALL_STAR_BY_HIP.get(int(hip))


def constellation_lines_resolved() -> List[Tuple[str, str, List[Tuple[float, float]]]]:
    """把星座连线解析成坐标序列。

    返回 [(星座缩写, 中文名, [(ra, dec), ...]), ...]，只保留端点齐全的折线，
    这样即使星表被裁剪也不会画出错误的连线。
    """
    result: List[Tuple[str, str, List[Tuple[float, float]]]] = []
    for abbr, polylines in CONSTELLATION_LINES.items():
        if abbr not in CONSTELLATIONS:
            continue
        cn = CONSTELLATIONS[abbr][0]
        for line in polylines:
            pts: List[Tuple[float, float]] = []
            ok = True
            for hip in line:
                star = ALL_STAR_BY_HIP.get(int(hip))
                if star is None:
                    ok = False
                    break
                pts.append((star.ra, star.dec))
            if ok and len(pts) >= 2:
                result.append((abbr, cn, pts))
    return result


def constellation_line_hips() -> List[Tuple[str, str, List[int]]]:
    """返回 [(星座缩写, 中文名, [HIP...]), ...]，渲染层用 HIP 索引更快。"""
    result: List[Tuple[str, str, List[int]]] = []
    for abbr, polylines in CONSTELLATION_LINES.items():
        cn = CONSTELLATIONS.get(abbr, ("", ""))[0]
        for line in polylines:
            if all(int(h) in ALL_STAR_BY_HIP for h in line) and len(line) >= 2:
                result.append((abbr, cn, [int(h) for h in line]))
    return result


def missing_hip_references() -> List[Tuple[str, int]]:
    """自检：返回连线上引用但星表缺失的 HIP 编号（开发用）。"""
    missing: List[Tuple[str, int]] = []
    for abbr, polylines in CONSTELLATION_LINES.items():
        for line in polylines:
            for hip in line:
                if int(hip) not in ALL_STAR_BY_HIP:
                    missing.append((abbr, int(hip)))
    return missing


def all_named_stars() -> List[Star]:
    """所有有名字的恒星（搜索排序用）。"""
    return [s for s in STAR_CATALOG if s.name or s.name_en]


def search_targets() -> List[Tuple[str, str, str]]:
    """搜索索引：[(显示名, 类型, 键), ...]。

    类型：star / messier / planet / sun / moon / constellation
    键与 SkyObject.key 保持一致，搜索后可直接高亮。
    """
    items: List[Tuple[str, str, str]] = []
    for s in STAR_CATALOG:
        if s.name:
            items.append((s.name, "star", f"star:{s.hip}"))
        if s.name_en:
            items.append((s.name_en, "star", f"star:{s.hip}"))
        items.append((f"HIP {s.hip}", "star", f"star:{s.hip}"))
    for m in MESSIER_CATALOG:
        items.append((m.name, "messier", f"messier:{m.name}"))
        items.append((m.name_cn, "messier", f"messier:{m.name}"))
        items.append((m.name_en, "messier", f"messier:{m.name}"))
    for abbr, (cn, latin) in CONSTELLATIONS.items():
        items.append((cn, "constellation", f"const:{abbr}"))
        items.append((latin, "constellation", f"const:{abbr}"))
    items.extend([
        ("太阳", "sun", "sun"), ("Sun", "sun", "sun"),
        ("月球", "moon", "moon"), ("Moon", "moon", "moon"),
        ("水星", "planet", "planet:mercury"), ("Mercury", "planet", "planet:mercury"),
        ("金星", "planet", "planet:venus"), ("Venus", "planet", "planet:venus"),
        ("火星", "planet", "planet:mars"), ("Mars", "planet", "planet:mars"),
        ("木星", "planet", "planet:jupiter"), ("Jupiter", "planet", "planet:jupiter"),
        ("土星", "planet", "planet:saturn"), ("Saturn", "planet", "planet:saturn"),
        ("天王星", "planet", "planet:uranus"), ("Uranus", "planet", "planet:uranus"),
        ("海王星", "planet", "planet:neptune"), ("Neptune", "planet", "planet:neptune"),
    ])
    return items


