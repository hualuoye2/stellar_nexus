def _check_ra_range() -> None:
    """导入时断言：所有内置坐标的 RA 必须落在 0~360°。

    这是针对"小时当成度"这类缺陷的**不变量检查**：赤经以小时计时最大只有 24，
    所以任何一次误抄都会让 RA < 24，被这条断言当场抓住，而不是等到星图画错位置
    才由用户发现。同理也检查 Dec 落在 −90~90。
    """
    groups = {
        "ADDITIONAL_STAR_COORDS": ((hip, v[0], v[1]) for hip, v in ADDITIONAL_STAR_COORDS.items()),
        "EXTRA_STARS": ((hip, v[0], v[1]) for hip, v in EXTRA_STARS.items()),
    }
    bad: List[str] = []
    for name, rows in groups.items():
        for hip, ra, dec in rows:
            if not (0.0 <= float(ra) < 360.0):
                bad.append(f"{name}[{hip}] 赤经 {ra}° 越界（疑似把小时当度写了）")
            if not (-90.0 <= float(dec) <= 90.0):
                bad.append(f"{name}[{hip}] 赤纬 {dec}° 越界")
    # 具名恒星额外查一遍（它们同时来自 DETAIL_STARS 与上面的附加表）
    for hip, cn, en, ra, dec, _m, _b, _s, _ab in DETAIL_STARS:
        if not (0.0 <= float(ra) < 360.0):
            bad.append(f"DETAIL_STARS[{hip}] {cn or en} 赤经 {ra}° 越界")
    if bad:
        raise ValueError("内置星表坐标越界：" + "；".join(bad[:6]))


_check_ra_range()


