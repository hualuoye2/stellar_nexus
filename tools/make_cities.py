def to_simplified(name: str) -> str:
    """把中文地名里的繁体字转成简体。"""
    return "".join(_TRAD_TO_SIMP.get(ch, ch) for ch in name)


def pick_chinese(alternates: str) -> str:
    """从别名串里挑出最合适的**简体**中文名。"""
    best = ""
    best_score = -1e9
    for part in alternates.split(","):
        name = part.strip()
        if not name or len(name) > 12 or not _CJK.search(name):
            continue
        if not re.fullmatch(r"[\u4e00-\u9fff·]+", name):
            continue
        score = 0.0
        score -= sum(1 for ch in name if ch in _TRADITIONAL_CHARS) * 4.0
        if name.endswith(_SUFFIX):
            score += 3.0
        if _PURE_CJK.match(name):
            score += 2.0
        score -= max(0, len(name) - 5) * 1.5
        if score > best_score:
            best_score, best = score, name
    return to_simplified(best)


