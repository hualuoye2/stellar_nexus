# 银河带的结构模型（表面亮度沿银经的变化 + 大暗带）
# ==============================================================================
# 这一节是**观测事实的参数化**，不是物理推导。定标依据：
#
#   1. 表面亮度沿银经的变化
#      银心方向（l=0）是全天空最亮的银河区域，反银心（l=180）大约暗 3~5 倍。
#      用 V 波段表面亮度（mag/arcsec²）折算成相对强度：
#          银心  μ_V ≈ 21.5  → 反银心 μ_V ≈ 23.0   （每等 2.512 倍，故约 4 倍）
#      再叠加人马-船底臂（l≈305~330，南天最亮的段落）与天鹅座星云
#      （l≈80，北天最亮的段落）两个局部增亮。
#
#   2. 大暗带（Great Rift）
#      从天鹅座（l≈80, b≈+1）一路斜劈到人马座（l≈355, b≈−2）、
#      再延伸到半人马座（l≈305, b≈+2），把夏季银河从中劈成两半。
#      这是最近的一条尘埃带，消光可达数等，所以画成"挖空"效果。
#      银经 0~50 一带（人马-盾牌座）也有大块暗星云（如 Pipe Nebula）。
#
# 视觉层用的都是这些**无量纲相对强度**，所以模型错了不会让星图"算错"，
# 只会让银河看起来不像；校验方式见 tools/check_milky_way.py。

#: 银河相对亮度随银经的变化（控制点，线性插值）
#: l=0 银心最亮 → l=180 反银心最暗；305~330 与 75~85 是两处局部峰
