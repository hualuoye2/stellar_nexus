@dataclass
class Star:
    """一颗恒星。"""

    hip: int                       # HIP 编号
    name: str                      # 中文名（可能为空）
    name_en: str                   # 英文名 / 拜耳命名
    ra: float                      # 赤经（度，J2000）
    dec: float                     # 赤纬（度，J2000）
    mag: float                     # 视星等
    bv: float                      # B-V 色指数
    spectral: str                  # 光谱型
    constellation: str = ""        # 所属星座（中文）
    constellation_abbr: str = ""   # 所属星座（三字母缩写）
    distance: Optional[float] = None   # 距离（光年）
    bayer: str = ""                # 拜耳命名（可选）

    @property
    def color_rgb(self) -> Tuple[int, int, int]:
        """按 B-V 计算显示颜色（延迟导入避免循环依赖）。"""
        from .utils import bv_to_rgb
        return bv_to_rgb(self.bv)

    def display_name(self) -> str:
        """优先中文名，其次英文名，最后 HIP 编号。"""
        return self.name or self.name_en or f"HIP {self.hip}"


@dataclass
class MessierObject:
    """一个深空天体（Messier / NGC / IC）。"""

    name: str                      # "M31"
    name_en: str                   # 英文常用名
    name_cn: str                   # 中文名
    ra: float                      # 赤经（度，J2000）
    dec: float                     # 赤纬（度，J2000）
    mag: float                     # 视星等
    mtype: str                     # 类型（中文）
    size: str                      # 视大小
    constellation: str = ""        # 所属星座（中文）
    desc: str = ""                 # 简介

    @property
    def display_name(self) -> str:
        return f"{self.name} {self.name_cn}" if self.name_cn else self.name


